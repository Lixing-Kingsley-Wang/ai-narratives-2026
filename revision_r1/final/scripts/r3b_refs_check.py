def existing():
    txt = (R1 / "inputs" / "Final Manuscript Submission LW jmir.txt").read_text(encoding="utf-8")
    block = txt[txt.rindex("References"):]
    refs = []
    for m in re.finditer(r"^(\d{1,2})\. (.+)$", block, re.M):
        s = m.group(2).strip()
        pmid = re.search(r"PMID:?\s*(\d+)", s)
        doi = re.search(r"(?:doi:|DOI:|https://doi\.org/)\s*(10\.\S+?)\.?(?:\s|$)", s, re.I)
        url = re.search(r"(https?://(?!doi\.org)\S+?)\.?(?:\s|$|\])", s)
        refs.append((f"E{m.group(1)}", s, pmid[1] if pmid else None, doi[1].rstrip(".") if doi else None, url[1] if url else None))
    assert len(refs) == 24, len(refs)
    return refs


def curl(url, data=None, head=False):
    cmd = ["curl", "-sS", "-L", "--max-time", "60", "-A", "Mozilla/5.0 (reference check; ai_narratives_study)"]
    if head:
        cmd += ["-o", "/dev/null", "-w", "%{http_code} %{url_effective}"]
    if data is not None:
        cmd += ["--data-binary", "@-"]
    r = subprocess.run(cmd + [url], input=data, capture_output=True)
    return r.stdout


def ncbi(endpoint, params, email):
    time.sleep(0.4)
    data = urllib.parse.urlencode({**params, "tool": TOOL, "email": email}).encode()
    return json.loads(curl(EU + endpoint, data=data))


